def test_teacher_forced_quality_when_candidate_changes_numerics(tmp_path: Path) -> None:
    # Given: original-baseline continuation/logits, generated by the actual numerical model.
    resident, backend, _ = runner(tmp_path)
    assert hasattr(resident, "create_oracles"), "sequential original-baseline oracle generation is absent"
    ids = ("calibration-calibration-00", "calibration-calibration-01")
    oracle = resident.create_oracles(ids)
    assert resident.quality(ids, oracle).valid
    original = backend.model.scale.forward
    # When: a wrong computation changes the same teacher-forced continuation's logits.
    backend.model.scale.forward = lambda value: original(value) + 3.0
    report = resident.quality(ids, oracle)
    # Then: raw numerical errors reject the model; no scalar-score fake is involved.
    assert not report.valid
    raw = json.loads(report.raw_path.read_text())["data"]
    assert len(raw["prompts"]) == 2
    assert all(p["valid_tokens"] == 32 for p in raw["prompts"])
    assert report.metrics["logits_relative_l2_max"] > 0.01


def test_short_decode_when_completion_record_is_incomplete(tmp_path: Path) -> None:
    # Given: a real generated single-request record, then a missing output token.
    from examples.c3_qwen3.runner_measure import score_waves
    from examples.c3_qwen3.runner_records import RunnerError, WaveRecord
    resident, _, prepared = runner(tmp_path)
    goal = next(g for g in prepared.contract.goals if g.id == "single")
    report = resident.measure(goal, goal.search_prompt_ids)
    waves = tuple(WaveRecord.model_validate(w) for w in json.loads(report.raw_path.read_text())["data"]["waves"])
    shortened = waves[-1].model_copy(update={"tokens": (waves[-1].tokens[0][:-1],)})
    # When / Then: incomplete execution cannot yield a native throughput score.
    with pytest.raises(RunnerError, match="incomplete"):
        score_waves(goal, (*waves[:-1], shortened))


