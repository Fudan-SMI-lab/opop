def test_wrong_operator_when_only_target_shape_falls_back(tmp_path: Path) -> None:
    # Given: short calibration uses the rewrite, while the formal long prompt calls old code.
    from tests.test_c3_model_binding import make_bundle
    resident, _, prepared = runner(tmp_path)
    ids = ("calibration-calibration-00", "calibration-calibration-01")
    threshold = max(sum(prepared.prompts_by_id[p].input_ids) for p in ids) + 32 * 7
    resident.binding.register_site("scale", ("scale",))
    oracle = resident.create_oracles(ids)
    resident.capture_fixtures(ids)
    body = ("def replace(site, call, params):\n"
            f"    if call.args[0] > {threshold}:\n        return site.module.original(*call.args)\n"
            "    return call.args[0] * factor\n")
    resident.bind(make_bundle(tmp_path / "candidate", body))
    assert resident.quality(ids, oracle).valid
    goal = prepared.contract.goals[0]
    # When: the single required same-shape warmup checks actual target dispatch.
    report = resident.measure(goal, goal.search_prompt_ids)
    # Then: no formal score is emitted for a shape-dependent fallback wrapper.
    assert not report.evaluation.valid
    assert "exclusively" in report.evaluation.detail


def test_stale_function_when_dispatch_changes_after_quality(tmp_path: Path) -> None:
    # Given: validated candidate dispatch and an obsolete original-forward pointer.
    from tests.test_c3_model_binding import make_bundle
    resident, backend, _ = runner(tmp_path)
    ids = ("calibration-calibration-00", "calibration-calibration-01")
    original = backend.model.scale.forward
    resident.binding.register_site("scale", ("scale",))
    oracle = resident.create_oracles(ids)
    resident.capture_fixtures(ids)
    resident.bind(make_bundle(tmp_path / "candidate", "def replace(site, call, params):\n    return call.args[0] * factor\n"))
    assert resident.quality(ids, oracle).valid
    # When: another caller silently replaces the installed dispatch.
    backend.model.scale.forward = original
    # Then: the runner rejects stale identity rather than silently repairing it before timing.
    assert hasattr(resident.binding, "verify_installed"), "dispatch identity validation is absent"
    with pytest.raises(RuntimeError, match="dispatch"):
        resident.binding.verify_installed()


def test_failed_measurement_when_weights_mutate_closes_runner(tmp_path: Path) -> None:
    # Given: a failing forward that also corrupts resident immutable weights.
    resident, backend, prepared = runner(tmp_path)
    def corrupt(value: float) -> float:
        backend.model.scale.weight = 3.0
        raise ArithmeticError("corrupted then failed")
    backend.model.scale.forward = corrupt
    goal = prepared.contract.goals[0]
    # When: failure occurs before normal post-measurement validation.
    report = resident.measure(goal, goal.search_prompt_ids)
    # Then: invalid data is retained and the poisoned model cannot be reused.
    assert not report.evaluation.valid
    assert resident.closed
