def now():return datetime.now(timezone.utc).isoformat()


def prepare(args,config):
    audit=read(args.replay/'terminal-audit.json');done=read(args.replay/'followup-completed.json')
    assert done['phase']=='completed'and audit['code_review']['fixed_execution_justified']and audit['core']==framework_source()
    frozen=audit['frozen_identities'].copy();cases={}
    sources={'qwen':'qwen-end-to-end-original-followup-20261029/qwen-original','fsdp':'fsdp-search-20261028/fsdp-search'}
    for case,rel in sources.items():
        row=done['results'][case];directory=Path(row['agent']['sandbox']);validate_proposal(directory)
        meta,_,files=load(Path(row['initial_snapshot']));assert meta['framework_source']==framework_source()
        assert sha(directory/'candidate.py')==row['candidate_sha256']==audit['roles'][case]['candidate_sha256']
        assert sha(directory/'proposal.json')==row['proposal_sha256']
        source=args.replay.parent/rel;search=ProjectSearch(config,source)
        parent=search.revisions.revision(json.loads(files['inputs/project.json'])['current_revision'])
        assert not parent.bundles
        assert search.request.portable()==json.loads(files['inputs/request.json'])
        discovery=read(source/'discovery.json');assert discovery['revision']==parent.id
        assert discovery['calls']==json.loads(files['inputs/calls.json'])and discovery['groups']==json.loads(files['inputs/groups.json'])
        assert search.request.continuous_steps==2 and search.request.warmup==2 and search.request.repeats==5
        assert len(search.request.diagnostic_metrics)==(4 if case=='fsdp'else 0)
        params=audit['code_review'][case+'_parameters']
        if case=='qwen':assert params=={}and read(directory/'proposal.json')['parameter_space']=={}
        else:
            assert params=={'keep_unsharded_blocks':2}
            assert read(directory/'proposal.json')['parameter_space']['params'][0]['choices']==[0,1,2,3,4]
        for p in [source/'project/current.json',source/'request.json',source/'prepared.json',source/'discovery.json',directory/'candidate.py',directory/'proposal.json',args.replay/'terminal-audit.json']:
            frozen[str(p)]=sha(p)
        cases[case]={'source':source,'parent':parent,'directory':directory,'selection':json.loads(files['inputs/selection.json']),
            'discovery':discovery,'parameters':params,'original_current':search.revisions.current().id,
            'adapter_sha256':search.prepared['adapter_sha256'],'controls_path':search.prepared['controls_path']}
    assert all(sha(p)==h for p,h in frozen.items())
    return cases,frozen


def main(args):
    os.umask(0o077);config=load_config(args.config,[]);config.usage.mode='observe_only';cases,frozen=prepare(args,config)
    definitions={k:{'source':str(d['source']),'parent':d['parent'].id,'source_current':d['original_current'],
        'candidate_sha256':sha(d['directory']/'candidate.py'),'proposal_sha256':sha(d['directory']/'proposal.json'),
        'adapter_sha256':d['adapter_sha256'],'parameters':d['parameters'],'controls_path':d['controls_path']}for k,d in cases.items()}
    if args.preflight:
        print(json.dumps({'status':'passed','core':framework_source(),'cases':definitions,'frozen_files':len(frozen),
            'sequence':['qwen-B','qwen-C','fsdp-B','fsdp-C-K2'],'disk':disk_observation(Path('/root/autodl-tmp'))}));return
    args.output.mkdir(parents=True,exist_ok=True);assert not(args.output/'protocol.json').exists()
    write_json(args.output/'protocol.json',{'at':now(),'core':framework_source(),'cases':definitions,'frozen_identities':frozen,
        'replay_audit_sha256':sha(args.replay/'terminal-audit.json'),'sequence':['qwen-B','qwen-C','fsdp-B','fsdp-C-K2'],
        'scope':'One fixed B/C per task, exact real generated bytes. Qwen empty parameters; FSDP generated default/declared primary K2, not best-of search. Original evaluator and original quality/constraints/2 continuous/2 warmup/5 clean/diagnostic metrics unchanged. Failed B skips dependent C. No observer, new agents, search, formal performance acceptance, Nsight, controls/reference copies, pointer publication or old-result rewrite. Both roles opened indexes and partial summaries but overclaimed causes and did not read producing diagnostic code. This execution does not validate those claims or adopt the prompt.',
        'disk':disk_observation(Path('/root/autodl-tmp'))})
    results={};identities={}
    for case,d in cases.items():
        try:
            branch=args.output/(case+'-fixed');parent=fork_run(d['source'],branch,revision_id=d['parent'].id);search=ProjectSearch(config,branch)
            assert parent.id==d['parent'].id and not parent.bundles
            assert search.prepared['adapter_sha256']==d['adapter_sha256']and search.prepared['controls_path']==d['controls_path']
            write_json(branch/'discovery.json',d['discovery'])
            bundle,_=search.bundle_from_outputs(d['directory'],d['selection'],parent,d['discovery'],'fixed-index-read-'+case)
            bundle=bundle.model_copy(update={'parameters':d['parameters']});candidate=search.revisions.stage(bundle)
            original={f.path:f.sha256 for f in parent.files};new={f.path:f.sha256 for f in candidate.files}
            assert all(new[k]==v for k,v in original.items())and new[bundle.installer]==definitions[case]['candidate_sha256']
            assert candidate.contract_ref==parent.contract_ref
            identities[case]={'baseline':parent.id,'candidate':candidate.id,'bundle':bundle.model_dump(mode='json'),
                'original_files':original,'candidate_files':new,'contract_ref':parent.contract_ref}
            write_json(args.output/'staged-identities.json',identities)
            baseline_valid=False
            for arm,revision in [('B',parent),('C',candidate)]:
                name=case+'-'+arm
                if arm=='C'and not baseline_valid:
                    results[name]={'status':'not_run','reason':'Fresh fixed baseline did not pass original quality/coverage.'};continue
                write_json(args.output/'state.json',{'at':now(),'phase':'running','stage':name})
                try:
                    run=search.execute(revision,name,'evaluate');path=args.output/(name+'-result.json');write_json(path,run)
                    valid=valid_run(run);constraints=constraints_for_runs([run],search.request.objective,search.prepared['evaluation'])if valid else[]
                    if arm=='B':baseline_valid=valid
                    results[name]={'status':'attempt_completed'if run.get('worker_pids_reaped')else'execution_error',
                        'worker_status':run['status'],'valid_run':valid,'constraints':constraints,'result':str(path),
                        'result_sha256':sha(path),'request':str(branch/'jobs'/name/'run/request.json'),'revision':revision.id,
                        'scope':'Quality/coverage and fixed constraints only; all timings diagnostic, no paired performance acceptance.'}
                except Exception:results[name]={'status':'execution_error','traceback':traceback.format_exc()}
                write_json(args.output/'followup-results.json',results)
                print(json.dumps({'at':now(),'endpoint':name,'status':results[name]['status'],'valid':results[name].get('valid_run')}),flush=True)
            assert search.revisions.current().id==parent.id
            assert ProjectSearch(config,d['source']).revisions.current().id==d['original_current']
        except Exception:results[case+'-setup']={'status':'execution_error','traceback':traceback.format_exc()}
        write_json(args.output/'followup-results.json',results)
    same=all(sha(p)==h for p,h in frozen.items())
    terminal={'phase':'completed'if same and all(v['status']=='attempt_completed'for v in results.values())else'completed_with_errors',
        'finished_at':now(),'results':results,'frozen_files_unchanged':same,'disk':disk_observation(Path('/root/autodl-tmp')),
        'scope':'Completion is not quality, feasibility or performance acceptance. No source or branch pointer publication.'}
    write_json(args.output/'state.json',terminal);write_json(args.output/'followup-completed.json',terminal)


