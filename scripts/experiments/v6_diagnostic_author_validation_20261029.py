"""One baseline/candidate observation with exact real-agent diagnostic bytes."""
import argparse
from datetime import datetime,timezone
import json
import os
from pathlib import Path
import traceback
from kernel_optimizer.runtime.execution import ExecutionRequest,LocalExecutor,write_json
from kernel_optimizer.runtime.provenance import framework_source
from scripts.experiments.v6_audit_fsdp_20261028 import read,sha
from scripts.experiments.v6_ddp_semantics_20261027 import disk_observation
from scripts.experiments.v6_diagnostic_author_20261029 import build_inputs


def now():return datetime.now(timezone.utc).isoformat()


def main(args):
    os.umask(0o077);audit=read(args.parent/'terminal-audit.json')
    assert audit['review']['execute_exact_bytes_once'] and audit['core']==framework_source()
    _,expected,index=build_inputs(args.parent.parent)
    probe=Path(audit['generated']['probe']);assert sha(probe)==audit['generated']['probe_sha256']
    expected[str(probe)]=sha(probe);expected[audit['generated']['plan']]=audit['generated']['plan_sha256']
    requests={k:Path(v['path'])for k,v in index['original_execution_requests'].items()}
    for p in requests.values():
        pointer=p.parents[3]/'project/current.json'
        assert read(pointer)['revision']=='b61996e1a998de911fa0412b595ef484b75dc79765d404aed835051e885b8a3c'
        expected[str(pointer)]=sha(pointer)
        request=read(p);task=request['parameters']['request']
        assert task['repeats']==5 and task['continuous_steps']==2 and task['warmup']==2
        assert request['parameters']['action']=='evaluate'
    assert all(sha(p)==h for p,h in expected.items())
    if args.preflight:
        print(json.dumps({'status':'passed','core':framework_source(),'probe_sha256':sha(probe),'frozen_files':len(expected),'sequence':['baseline','candidate']}));return
    args.output.mkdir(parents=True,exist_ok=True);assert not(args.output/'protocol.json').exists()
    write_json(args.output/'protocol.json',{'at':now(),'core':framework_source(),'parent':str(args.parent),
        'parent_audit_sha256':sha(args.parent/'terminal-audit.json'),'probe':str(probe),'probe_sha256':sha(probe),
        'plan_sha256':audit['generated']['plan_sha256'],'source_requests':{k:str(v)for k,v in requests.items()},
        'source_reference':index['independent_source_reference'],'frozen_identities':expected,
        'sequence':['baseline-observed','candidate-observed'],'known_probe_limitations':audit['review']['limitations'],
        'scope':'Exact generated bytes, no manual repair. Each original evaluator runs once. Original unobserved failure retained. No Agent/search/acceptance/native/control-copy/pointer change. All timing diagnostic, observer effects possible.',
        'disk':disk_observation(Path('/root/autodl-tmp'))})
    results={}
    for arm in ['baseline','candidate']:
        name=arm+'-observed';write_json(args.output/'state.json',{'phase':'running','stage':name,'at':now()})
        request=ExecutionRequest.model_validate(read(requests[arm]))
        diagnostic={'original_entry':str(request.entry),'original_function':request.function,
            'independent_reference':index['independent_source_reference']['path'],'arm':name}
        updated=request.model_copy(update={'entry':probe,'function':'run','output':args.output/name,'wait_for_devices':True,
            'parameters':{**request.parameters,'diagnostic_context':diagnostic}})
        try:
            run=LocalExecutor().run(updated);path=args.output/(name+'-result.json');write_json(path,run)
            side=args.output/name/'diagnostic-index-rank-0.json'
            results[name]={'status':'attempt_completed'if run.get('worker_pids_reaped')and side.exists()else'execution_error',
                'worker_status':run['status'],'result':str(path),'result_sha256':sha(path),
                'request':str(args.output/name/'request.json'),'diagnostic_index':str(side)if side.exists()else None,
                'interpretation':'Attempt completion is not full quality or diagnostic correctness; inspect original exception/evidence/worker separately.'}
        except Exception:results[name]={'status':'execution_error','traceback':traceback.format_exc()}
        write_json(args.output/'followup-results.json',results);print(json.dumps({'at':now(),'endpoint':name,**results[name]}),flush=True)
    same=all(sha(p)==h for p,h in expected.items())
    terminal={'phase':'completed'if same and all(r['status']=='attempt_completed'for r in results.values())else'completed_with_errors',
        'finished_at':now(),'results':results,'all_frozen_hashes_unchanged':same,'disk':disk_observation(Path('/root/autodl-tmp'))}
    write_json(args.output/'state.json',terminal);write_json(args.output/'followup-completed.json',terminal)


if __name__=='__main__':
    p=argparse.ArgumentParser(__doc__)
    for name in ['parent','output']:p.add_argument('--'+name,type=Path,required=True)
    p.add_argument('--preflight',action='store_true');main(p.parse_args())
